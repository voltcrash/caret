import { contract } from "@caret/contracts";
import { isAppRoute, type AppRoute } from "@caret/contracts/contract";
import { allOperations } from "@caret/backend/policies/operations";
import { readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { webOperationIds } from "../src/functions/operations/web-operations";

const src = resolve(import.meta.dirname, "../src");
const functionsDir = resolve(src, "functions/operations");
const routes = contract as unknown as Record<string, Record<string, AppRoute>>;
const handWritten = new Set(["input.ts", "web-operations.ts"]);

// Formatting changes whitespace; bindings are the reproducible contract.
const normalize = (value: string): string =>
  value.replaceAll(/\s/g, "").replaceAll(/,(?=[)}\]])/g, "");

function emit(files: Map<string, string>, check: boolean): void {
  for (const [file, source] of files) {
    if (!check) {
      writeFileSync(file, source);
      continue;
    }
    let actual: string | undefined;
    try {
      actual = readFileSync(file, "utf8");
    } catch {
      actual = undefined;
    }
    if (actual === undefined || normalize(actual) !== normalize(source)) {
      throw new Error(`Stale generated operation file: ${file}`);
    }
  }
}

/** Explicit Start route declarations for retained HTTP; no runtime matcher. */
function httpRoutes(): Map<string, string> {
  const files = new Map<string, string>();
  const paths = Map.groupBy(allOperations(), ({ route }) =>
    `/api${route.path}`.replace(/\/$/, ""),
  );
  for (const [path, operations] of paths) {
    const route = path.replace(/:(\w+)/g, "$$$1");
    const handlers = operations
      .map(
        ({ id, route }) =>
          `      ${route.method}: async ({ request, params }) => await serveOperation(request, "${id}", params),`,
      )
      .join("\n");
    files.set(
      resolve(src, "routes", `${route.slice(1).replaceAll("/", ".")}.ts`),
      `// Generated by scripts/generate-operations.ts. External protocols and old-tab adapters.\nimport { createFileRoute } from "@tanstack/solid-router";\nimport { serveOperation, unknownApi } from "../server/http.server";\n\nexport const Route = createFileRoute("${route}")({\n  server: {\n    handlers: {\n${handlers}\n      ANY: async ({ request }) => await unknownApi(request),\n    },\n  },\n});\n`,
    );
  }
  return files;
}

function functionName(id: string): { group: string; name: string } {
  const [group = "", operation = ""] = id.split(".");
  const route = routes[group]?.[operation];
  if (route === undefined || !isAppRoute(route)) {
    throw new Error(`Unknown contract operation: ${id}`);
  }
  return {
    group,
    name: `${group}${operation[0]?.toUpperCase()}${operation.slice(1)}`,
  };
}

/** One narrow server function per web operation, named for its ID. */
function serverFunctions(): Map<string, string> {
  const files = new Map<string, string>();
  const ids = [...webOperationIds].toSorted();
  const groups = Map.groupBy(ids, (id) => functionName(id).group);
  for (const [group, groupIds] of groups) {
    const functions = groupIds.map((id) => {
      const [g = "", operation = ""] = id.split(".");
      const method = routes[g]?.[operation]?.method === "GET" ? "GET" : "POST";
      return `export const ${functionName(id).name} = createServerFn({ method: "${method}" })\n  .validator(operationInput)\n  .handler(\n    async ({ context, data }) =>\n      await callOperation(context.services, "${id}", data),\n  );\n`;
    });
    files.set(
      resolve(functionsDir, `${group}.ts`),
      `// Generated by scripts/generate-operations.ts from web-operations.ts.\nimport { createServerFn } from "@tanstack/solid-start";\nimport { callOperation } from "../../server/operation.server";\nimport { operationInput } from "./input";\n\n${functions.join("\n")}`,
    );
  }
  const imports = [...groups.keys()]
    .map((group) => `import * as ${group}Fns from "./${group}";`)
    .join("\n");
  const entries = ids
    .map((id) => {
      const { group, name } = functionName(id);
      return `  "${id}": ${group}Fns.${name},`;
    })
    .join("\n");
  files.set(
    resolve(functionsDir, "index.ts"),
    `// Generated by scripts/generate-operations.ts from web-operations.ts.\n${imports}\n\n/**\n * Server functions the browser operation client may call, by operation ID.\n * Unit tests and Storybook substitute a stand-in map for this module.\n */\nexport const webOperations = {\n${entries}\n};\n`,
  );
  return files;
}

export function generateOperations(check = false): void {
  const functions = serverFunctions();
  if (check) {
    const expected = new Set(
      [...functions.keys()].map((file) => file.slice(functionsDir.length + 1)),
    );
    for (const name of readdirSync(functionsDir)) {
      if (!handWritten.has(name) && !expected.has(name)) {
        throw new Error(`Unexpected operation function file: ${name}`);
      }
    }
  } else {
    for (const name of readdirSync(functionsDir)) {
      if (!handWritten.has(name)) rmSync(resolve(functionsDir, name));
    }
  }
  emit(httpRoutes(), check);
  emit(functions, check);
}

generateOperations(process.argv.includes("--check"));
