import { expect, it } from "vite-plus/test";
import { getIpKey } from "../../src/policies/ip-key";

it.for([
  ["203.0.113.7", "203.0.113.7"],
  ["2001:db8:1234:5678::1", "2001:db8:1234:5600::/56"],
  ["2001:0DB8:0000:12ff:abcd::", "2001:db8:0:1200::/56"],
  ["::1", "::/56"],
  ["::", "::/56"],
  ["fe80::1%eth0", "fe80::/56"],
  ["::ffff:192.168.1.1", "::/56"],
  ["2001:db8::", "2001:db8::/56"],
  ["1:0:0:0:0:0:0:8", "1::/56"],
  ["2001:0:0:1ff::", "2001:0:0:100::/56"],
] as const)("keys %s as %s", ([ip, key]) => {
  expect(getIpKey(ip)).toBe(key);
});
