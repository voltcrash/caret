import { contract } from "@caret/contracts";
import { isAppRoute, type AppRoute } from "@caret/contracts/contract";
import { allOperations } from "@caret/backend/policies/operations";
import { readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { webOperationIds } from "../src/functions/operations/web-operations";

const src = resolve(import.meta.dirname, "../src");
const functionsDir = resolve(src, "functions/operations");
const routes = contract as unknown as Record<string, Record<string, AppRoute>>;

const header = "// Generated by scripts/generate-operations.ts";

/** Formatting changes whitespace and trailing commas, never string contents. */
function normalize(value: string): string {
  let out = "";
  let quote: string | undefined;
  for (let i = 0; i < value.length; i++) {
    const char = value[i] as string;
    if (quote !== undefined) {
      out += char;
      if (char === "\\") out += value[++i] ?? "";
      else if (char === quote) quote = undefined;
    } else if (char === "/" && value[i + 1] === "/") {
      // A line comment ends at its newline; keep that boundary.
      const end = value.indexOf("\n", i);
      out += `${value.slice(i, end === -1 ? undefined : end).trimEnd()}\n`;
      i = end === -1 ? value.length : end;
    } else if (char === '"' || char === "'" || char === "`") {
      quote = char;
      out += char;
    } else if (char === ",") {
      const next = /\S/.exec(value.slice(i + 1))?.[0];
      if (next !== ")" && next !== "}" && next !== "]") out += char;
    } else if (!/\s/.test(char)) {
      out += char;
    }
  }
  return out;
}

// This generator's header, or the retired generate-http-routes.ts one.
const headers = [header, "// Generated by scripts/generate-http-routes.ts"];

function isGenerated(file: string): boolean {
  const source = readFileSync(file, "utf8");
  return headers.some((prefix) => source.startsWith(prefix));
}

/** Writes (or checks) `files`; removes (or rejects) stale generated files in `directory`. */
function emit(
  directory: string,
  files: Map<string, string>,
  check: boolean,
): void {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const file = resolve(directory, entry.name);
    if (!entry.isFile() || files.has(file) || !isGenerated(file)) continue;
    if (check) throw new Error(`Stale generated operation file: ${file}`);
    rmSync(file);
  }
  for (const [file, source] of files) {
    if (!check) {
      writeFileSync(file, source);
      continue;
    }
    let actual: string | undefined;
    try {
      actual = readFileSync(file, "utf8");
    } catch {
      actual = undefined;
    }
    if (actual === undefined || normalize(actual) !== normalize(source)) {
      throw new Error(`Stale generated operation file: ${file}`);
    }
  }
}

/** Explicit Start route declarations for retained HTTP; no runtime matcher. */
function httpRoutes(): Map<string, string> {
  const files = new Map<string, string>();
  const paths = Map.groupBy(allOperations(), ({ route }) =>
    `/api${route.path}`.replace(/\/$/, ""),
  );
  for (const [path, operations] of paths) {
    const route = path.replace(/:(\w+)/g, "$$$1");
    const handlers = operations
      .map(
        ({ id, route }) =>
          `      ${route.method}: async ({ request, params }) => await serveOperation(request, "${id}", params),`,
      )
      .join("\n");
    files.set(
      resolve(src, "routes", `${route.slice(1).replaceAll("/", ".")}.ts`),
      `${header}. External protocols and old-tab adapters.\nimport { createFileRoute } from "@tanstack/solid-router";\nimport { serveOperation, unknownApi } from "../server/http.server";\n\nexport const Route = createFileRoute("${route}")({\n  server: {\n    handlers: {\n${handlers}\n      ANY: async ({ request }) => await unknownApi(request),\n    },\n  },\n});\n`,
    );
  }
  return files;
}

function functionName(id: string): { group: string; name: string } {
  const [group = "", operation = ""] = id.split(".");
  const route = routes[group]?.[operation];
  if (route === undefined || !isAppRoute(route)) {
    throw new Error(`Unknown contract operation: ${id}`);
  }
  return {
    group,
    name: `${group}${operation[0]?.toUpperCase()}${operation.slice(1)}`,
  };
}

/** One narrow server function per web operation, named for its ID. */
function serverFunctions(): Map<string, string> {
  const files = new Map<string, string>();
  const ids = [...webOperationIds].toSorted();
  const groups = Map.groupBy(ids, (id) => functionName(id).group);
  for (const [group, groupIds] of groups) {
    const functions = groupIds.map((id) => {
      const [g = "", operation = ""] = id.split(".");
      const method = routes[g]?.[operation]?.method === "GET" ? "GET" : "POST";
      return `export const ${functionName(id).name} = createServerFn({ method: "${method}" })\n  .validator(operationInput)\n  .handler(\n    async ({ context, data }) =>\n      await callOperation(context.services, "${id}", data),\n  );\n`;
    });
    files.set(
      resolve(functionsDir, `${group}.ts`),
      `${header} from web-operations.ts.\nimport { createServerFn } from "@tanstack/solid-start";\nimport { callOperation } from "../../server/operation.server";\nimport { operationInput } from "./input";\n\n${functions.join("\n")}`,
    );
  }
  const imports = [...groups.keys()]
    .map((group) => `import * as ${group}Fns from "./${group}";`)
    .join("\n");
  const entries = ids
    .map((id) => {
      const { group, name } = functionName(id);
      return `  "${id}": ${group}Fns.${name},`;
    })
    .join("\n");
  files.set(
    resolve(functionsDir, "index.ts"),
    `${header} from web-operations.ts.\n${imports}\n\n/**\n * Server functions the browser operation client may call, by operation ID.\n * Unit tests and Storybook substitute a stand-in map for this module.\n */\nexport const webOperations = {\n${entries}\n};\n`,
  );
  return files;
}

export function generateOperations(check = false): void {
  emit(resolve(src, "routes"), httpRoutes(), check);
  emit(functionsDir, serverFunctions(), check);
}

generateOperations(process.argv.includes("--check"));
