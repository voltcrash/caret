import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { allOperations } from "@oxytype/backend/policies/operations";

/** Explicit Start declarations, derived from the frozen contracts, with no runtime matcher. */
export function generateHttpRoutes(check = false): void {
  const paths = Map.groupBy(allOperations(), ({ route }) =>
    `/api${route.path}`.replace(/\/$/, ""),
  );
  for (const [path, operations] of paths) {
    const route = path.replace(/:(\w+)/g, "$$$1");
    const handlers = operations
      .map(
        ({ id, route }) =>
          `      ${route.method}: async ({ request, params }) => await serveOperation(request, "${id}", params),`,
      )
      .join("\n");
    const source = `// Generated by scripts/generate-http-routes.ts. External protocols and temporary old-tab adapters.\nimport { createFileRoute } from "@tanstack/solid-router";\nimport { serveOperation, unknownApi } from "../server/http.server";\n\nexport const Route = createFileRoute("${route}")({\n  server: {\n    handlers: {\n${handlers}\n      ANY: async ({ request }) => await unknownApi(request),\n    },\n  },\n});\n`;
    const file = resolve(
      import.meta.dirname,
      "../src/routes",
      `${route.slice(1).replaceAll("/", ".")}.ts`,
    );
    // Formatting changes whitespace; route bindings are the reproducible contract.
    if (check) {
      const normalize = (value: string): string =>
        value.replaceAll(/\s/g, "").replaceAll(/,(?=[)}\]])/g, "");
      const actual = normalize(readFileSync(file, "utf8"));
      if (actual !== normalize(source)) {
        throw new Error(`Stale HTTP route: ${file}`);
      }
    } else {
      writeFileSync(file, source);
    }
  }
}

generateHttpRoutes(process.argv.includes("--check"));
