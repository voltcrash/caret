export function getDefaultConfig(): Config {
  const defaults = ConfigSchema.parse({
    ...structuredClone(obj),
    ...projectEngineConfig({}),
  });
  // Enumeration order controls legacy full-import preference sequencing.
  return Object.fromEntries(
    fieldOrder.map((key) => [key, defaults[key]]),
  ) as Config;
}
