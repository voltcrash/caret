import { readFileSync, writeFileSync } from "node:fs";

/** Generate only the audited application/Storybook subset, including data-driven names. */
export function generateIconData(): string {
  const root = new URL("../icons/", import.meta.url);
  const selection = JSON.parse(
    readFileSync(new URL("selection.json", root), "utf8"),
  ) as Record<string, Record<string, string>>;
  const definitions = new Map<string, string>();
  const lines = [
    "/*! Font Awesome Free 7.3.1 by @fontawesome - https://fontawesome.com",
    " * Icons: CC BY 4.0 - https://creativecommons.org/licenses/by/4.0/",
    " * Copyright 2026 Fonticons, Inc. Paths unchanged; selected/packaged by Caret.",
    " */",
    "// Generated by generate-fontawesome-types.ts; edit icons/selection.json and SVG sources.",
  ];
  for (const files of Object.values(selection)) {
    for (const file of Object.values(files)) {
      if (definitions.has(file)) continue;
      const svg = readFileSync(new URL(file, root), "utf8");
      const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
      const paths = [...svg.matchAll(/<path[^>]* d="([^"]+)"/g)].map(
        (match) => match[1],
      );
      if (viewBox === undefined || paths.length !== 1) {
        throw new Error(`Unsupported icon ${file}`);
      }
      const name = `glyph${definitions.size}`;
      definitions.set(file, name);
      lines.push(
        `const ${name} = ${JSON.stringify({ viewBox, path: paths[0] })};`,
      );
    }
  }
  lines.push("export const icons = {");
  for (const [variant, files] of Object.entries(selection)) {
    lines.push(`  ${variant}: {`);
    for (const [name, file] of Object.entries(files)) {
      lines.push(`    ${JSON.stringify(name)}: ${definitions.get(file)},`);
    }
    lines.push("  },");
  }
  lines.push("} as const;", "");
  const output = lines.join("\n");
  return output;
}

export function writeIconData(): void {
  const target = new URL("../src/ts/icons.ts", import.meta.url);
  const output = generateIconData();
  let current: string | undefined;
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* First generation. */
  }
  if (current !== output) writeFileSync(target, output);
}
